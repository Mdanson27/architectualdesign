import assert from 'node:assert/strict';
import * as THREE from 'three';
import {revealObstructedDoors} from '../src/phase2/door-apertures.js';
const mesh=new THREE.Mesh(new THREE.BoxGeometry(2.8,2.7,.30),new THREE.MeshStandardMaterial());
mesh.position.set(0,1.35,0);mesh.updateMatrixWorld(true);
const box=new THREE.Box3().setFromObject(mesh);
const wall={mesh,box,category:'walls',layer:{level:'ground'}};
const windowSource=new THREE.Group();
windowSource.userData.sourceGUIDs=['window-IFC-guid'];
const w={position:new THREE.Vector3(0,1.3,0),width:1.8,height:2.0,alongX:true,group:windowSource};
const sourceWindow={windows:[w]};
const material=new THREE.MeshStandardMaterial();
const snapshot=Array.from(mesh.geometry.attributes.position.array);
const audit=revealObstructedDoors(material,{doors:[]},[wall],()=>true,sourceWindow);
assert.equal(audit.windowObstructedCount,1);
assert.equal(audit.obstructedCount,0);
assert.equal(audit.windowCount,1);
assert.equal(audit.visualCuts.length,1);
assert.equal(audit.visualCuts[0].kind,'window');
assert(Math.abs(audit.visualCuts[0].height.x-.315)<1e-8);
assert(material.version>0);
assert.deepEqual(Array.from(mesh.geometry.attributes.position.array),snapshot,'the original walls must not change');
const shader={uniforms:{},vertexShader:'#include <begin_vertex>',fragmentShader:'#include <clipping_planes_fragment>'};
material.onBeforeCompile(shader,{});
assert(shader.fragmentShader.includes('uDoorCount'));
assert(shader.fragmentShader.includes('discard'));
assert(shader.vertexShader.includes('vHouseWorldPoint'));
audit.restore();
assert.equal(material.onBeforeCompile,THREE.Material.prototype.onBeforeCompile);
console.log(JSON.stringify({passed:true,windowOcclusionCuts:audit.windowObstructedCount,IFCWallGeometryUnmodified:true,shaderHookActive:true,shaderRestore:true}));
